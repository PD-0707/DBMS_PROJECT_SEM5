CREATE TABLE IF NOT EXISTS USERS (
    USERS_ID TEXT PRIMARY KEY,
    USERS_NAME TEXT,
    EMAIL TEXT,
    PASSWD TEXT,
    BIO TEXT,
    GENDER TEXT
);

CREATE TABLE IF NOT EXISTS PREFERENCE_NEW (
    PREF_ID TEXT PRIMARY KEY,
    USER_ID TEXT NOT NULL,
    PREFERRED_GENDER TEXT,
    MIN_AGE INTEGER,
    MAX_AGE INTEGER,
    FOREIGN KEY (USER_ID) REFERENCES USERS (USERS_ID)
);

CREATE TABLE IF NOT EXISTS MATCH (
    M_ID TEXT PRIMARY KEY,
    MATCHED_ON TEXT,  -- Store as 'YYYY-MM-DD'
    USERS_ID1 TEXT,
    USERS_ID2 TEXT,
    USERS_ID TEXT,
    FOREIGN KEY(USERS_ID) REFERENCES USERS(USERS_ID)
);

CREATE TABLE IF NOT EXISTS SUBSCRIPTION (
    SUB_ID TEXT PRIMARY KEY,
    USERS_ID TEXT,
    PLAN_TYPE TEXT,
    START_DAY TEXT,   -- Store as 'YYYY-MM-DD'
    END_DAY TEXT,     -- Store as 'YYYY-MM-DD'
    SUB_STATUS TEXT,
    FOREIGN KEY(USERS_ID) REFERENCES USERS(USERS_ID)
);

CREATE TABLE IF NOT EXISTS PHOTO (
    PHOTO_ID TEXT PRIMARY KEY,
    USERS_ID TEXT,
    PHOTO_URL TEXT,
    UPLOAD_TIME TEXT,  -- Store as 'HH:MM:SS'
    CAPTION TEXT,
    FOREIGN KEY(USERS_ID) REFERENCES USERS(USERS_ID)
);

CREATE TABLE IF NOT EXISTS LIKE_TABLE (
    LIKE_ID TEXT PRIMARY KEY,
    LIKED_ID TEXT,
    LIKER_ID TEXT,
    LIKE_TIME TEXT,   -- Store as 'HH:MM:SS'
    USERS_ID TEXT,
    FOREIGN KEY(USERS_ID) REFERENCES USERS(USERS_ID)
);

CREATE TABLE IF NOT EXISTS REPORT (
    REPORT_ID TEXT PRIMARY KEY,
    REPORTER_ID TEXT,
    REPORTED_ID TEXT,
    REASON TEXT,
    REPORT_DATE TEXT,  -- Store as 'YYYY-MM-DD'
    USERS_ID TEXT,
    FOREIGN KEY(USERS_ID) REFERENCES USERS(USERS_ID)
);

CREATE TABLE IF NOT EXISTS CHAT (
    CHAT_ID TEXT PRIMARY KEY,          
    CHATROOM_ID TEXT,                  
    M_ID TEXT,
    SENDER_ID TEXT,
    RECEIVER_ID TEXT,
    CONTENT TEXT,
    CHAT_TIMESTAMP TEXT,
    FOREIGN KEY (M_ID) REFERENCES MATCH(M_ID)
);


CREATE TABLE IF NOT EXISTS LOCATION (
    LOC_ID TEXT PRIMARY KEY,
    CITY TEXT,
    USERS_STATE TEXT,
    COUNTRY TEXT,
    USERS_ID TEXT,
    FOREIGN KEY(USERS_ID) REFERENCES USERS(USERS_ID)
);

CREATE TABLE IF NOT EXISTS PHONE_NUMBER (
    PHONE_NO INTEGER,
    USERS_ID TEXT,
    FOREIGN KEY(USERS_ID) REFERENCES USERS(USERS_ID)
);

CREATE TABLE IF NOT EXISTS PREF_LOCATION (
    CITY TEXT,
    USERS_STATE TEXT,
    COUNTRY TEXT,
    P_ID TEXT,
    FOREIGN KEY(P_ID) REFERENCES PREFERENCE(P_ID)
);



CREATE TABLE IF NOT EXISTS INTERESTS (
    INT_ID TEXT PRIMARY KEY,
    INTEREST TEXT,
    USERS_ID TEXT,
    FOREIGN KEY(USERS_ID) REFERENCES USERS(USERS_ID)
);
